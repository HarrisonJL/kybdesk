# KYB Desk - EntityStanding v2. A know-your-business desk for UK companies:
# approvals that expire, a cheap tripwire that revokes them when the public
# register changes, batch checks, and a per-company history.
#
# It builds on EntityStanding v1 (0xC332c97876643E5037F5a8069Eb92b442c70ae49)
# and does not re-derive its core: the deterministic spine (the contract
# builds every Companies House / GLEIF URL; status, deadlines, officers and
# filings are parsed with plain code; identity is bound on every page and,
# optionally, through the LEI), the LLM early-warning reader that can only
# DOWNGRADE GOOD_STANDING to AT_RISK with a verbatim quote, and the
# fail-closed UNVERIFIED are v1's. Every line from the imports down to the
# storage classes (the parsers, _evaluate, the fetch helpers, the reader) is
# v1's, byte for byte. The storage classes gain fields, and the contract
# class below gains the methods listed here:
#
# 1. valid_until. A GOOD_STANDING approval lasts APPROVAL_DAYS at most, and
#    never reaches the start of the day a filing deadline falls - the one
#    thing about a company's standing that is known in advance.
# 2. probe(). One page fetch, no LLM: re-reads the fields the approval rests
#    on and revokes it at once if any changed. Re-attesting restores it.
# 3. attest_batch(): up to MAX_BATCH companies in one transaction.
# 4. get_history() / get_approval(): the company's own attestation chain,
#    and the reason an approval does or doesn't hold. is_approved() is the
#    consumer view.
#
# Studio Next port of contracts/kyb_desk.py (the locally-tested,
# GenVM v0.2.11 source of truth), generated by scripts/port_to_studio_next.py.
# Only GenVM import / decorator / base-class / message spellings differ.
